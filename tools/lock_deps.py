"""Write hash-locked requirement files from the packages installed in .venv.

Every package is pinned to an exact version plus the SHA-256 of each of its published files
(read from PyPI's JSON API), so `pip install --require-hashes` refuses anything that differs
from what was tested.

Usage:  .venv/Scripts/python tools/lock_deps.py
"""
from __future__ import annotations

import json
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = {"pyside6-essentials", "pyside6-addons", "shiboken6"}
SKIP = {"pip", "wheel", "pip-tools"}


def installed() -> dict[str, str]:
    out = subprocess.run([sys.executable, "-m", "pip", "list", "--format=json"],
                         capture_output=True, text=True, check=True).stdout
    norm = lambda n: n.lower().replace("_", "-")  # noqa: E731 - PEP 503 style names
    return {norm(p["name"]): p["version"] for p in json.loads(out) if norm(p["name"]) not in SKIP}


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def write(path: Path, header: str, pkgs: dict[str, str], include: str | None = None) -> None:
    lines = [header, "# Generated by tools/lock_deps.py - do not edit by hand.", ""]
    if include:
        lines += [f"-r {include}", ""]
    for name in sorted(pkgs):
        hs = hashes(name, pkgs[name])
        lines.append(f"{name}=={pkgs[name]} \\")
        lines += [f"    --hash=sha256:{h} \\" for h in hs[:-1]]
        lines.append(f"    --hash=sha256:{hs[-1]}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path.name}: {len(pkgs)} packages")


def main() -> None:
    pkgs = installed()
    runtime = {k: v for k, v in pkgs.items() if k in RUNTIME}
    dev = {k: v for k, v in pkgs.items() if k not in RUNTIME}
    write(ROOT / "requirements.txt", "# SwiftCut runtime dependencies (exact versions + checksums).", runtime)
    write(ROOT / "requirements-dev.txt", "# Development, testing and packaging tools.", dev, "requirements.txt")


if __name__ == "__main__":
    main()
